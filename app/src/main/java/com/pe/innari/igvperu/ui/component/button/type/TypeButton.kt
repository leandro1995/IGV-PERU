package com.pe.innari.igvperu.ui.component.button.type

/**
 * Enumeración que define las variantes o tipos disponibles para [com.pe.innari.igvperu.ui.component.button.ButtonComponent].
 */
enum class TypeButton {
    /** Botón principal con colores sólidos primarios. */
    PRIMARY,

    /** Botón secundario con contenedor primario variante. */
    SECONDARY,

    /** Botón con bordes delineados (outline). */
    OUTLINE,

    /** Botón de acción destructiva o de alerta (con colores de error). */
    DESTRUCTIVE
}
