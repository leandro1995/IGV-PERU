package com.pe.innari.igvperu.ui.component.bottomnavigation.type

import com.pe.innari.igvperu.ui.component.bottomnavigation.BottomNavigationComponent

/**
 * Define los tipos de navegación disponibles para el componente [BottomNavigationComponent].
 */
enum class TypeBottomNavigation {
    /**
     * Barra de navegación estándar en la parte inferior de la pantalla.
     */
    BOTTOM,

    /**
     * Riel de navegación lateral, generalmente utilizado en dispositivos de pantalla ancha.
     */
    RAIL
}