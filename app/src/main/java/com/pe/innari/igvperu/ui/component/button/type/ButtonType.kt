package com.pe.innari.igvperu.ui.component.button.type

/**
 * Define los tipos de botones disponibles en el sistema de diseño.
 * Cada tipo representa una jerarquía visual o propósito específico.
 */
enum class ButtonType {
    /** Botón principal para acciones de alta importancia. */
    PRIMARY,
    /** Botón secundario para acciones de menor relevancia. */
    SECONDARY,
    /** Botón con borde para acciones alternativas. */
    OUTLINED,
    /** Botón de estilo de error para acciones irreversibles o peligrosas. */
    DESTRUCTIVE
}